#!/usr/bin/env python3
"""Keep release channels and their pinned versions in one place.

`VERSION` is the repository release. Install pins advance only after their
package is verified, so a pin may intentionally be older than `VERSION`.
`release-matrix.json` records that mapping; `docs/release-channels.md` is the
generated human view. `--check` fails when a pin, the index, or the rendered
page drifts from the matrix.
"""

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
MATRIX_FILE = "release-matrix.json"
PAGE_FILE = "docs/release-channels.md"
DEV_DOC_GLOB = "INSTALL*dev*.md"
WORKBUDDY_DOC = "INSTALL.workbuddy.md"
VERSION_TAG = re.compile(r"v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?")
WORKBUDDY_SOURCE = re.compile(
    r'WORKBUDDY_SOURCE="https://plugin\.springbrand\.ai/releases/(v[^/]+)/workbuddy/springbrand-workbuddy\.zip"'
)
WORKBUDDY_VERSION = re.compile(r'WORKBUDDY_VERSION="([^"]+)"')


class MatrixError(Exception):
    pass


def load_matrix(root: Path = ROOT) -> dict:
    try:
        return json.loads((root / MATRIX_FILE).read_text())
    except FileNotFoundError as error:
        raise MatrixError(f"{MATRIX_FILE} is missing") from error
    except json.JSONDecodeError as error:
        raise MatrixError(f"{MATRIX_FILE} is not valid JSON: {error}") from error


def require(mapping: dict, key: str, where: str):
    value = mapping.get(key)
    if value in (None, "", {}, []):
        raise MatrixError(f"{where}: missing {key!r}")
    return value


def validate_matrix(matrix: dict) -> None:
    if matrix.get("schemaVersion") != 1:
        raise MatrixError("release-matrix.json: schemaVersion must be 1")
    channels = require(matrix, "channels", MATRIX_FILE)
    for name in ("stable", "development"):
        if name not in channels:
            raise MatrixError(f"release-matrix.json: missing channel {name!r}")
    for name, channel in channels.items():
        where = f"release-matrix.json: channels.{name}"
        require(channel, "label", where)
        tag = require(channel, "pluginTag", where)
        version = require(channel, "pluginVersion", where)
        if tag != f"v{version}":
            raise MatrixError(f"{where}: pluginTag {tag!r} does not match pluginVersion {version!r}")
        entry = require(channel, "installEntry", where)
        if name == "development" and "dev" not in entry:
            raise MatrixError(f"{where}: development entry must be a dev document")
        cli = require(channel, "cli", where)
        require(cli, "version", f"{where}.cli")
        require(cli, "distTag", f"{where}.cli")
    host_pins = require(matrix, "hostPins", MATRIX_FILE)
    for name, pin in host_pins.items():
        where = f"release-matrix.json: hostPins.{name}"
        version = require(pin, "version", where)
        source = require(pin, "source", where)
        if f"/releases/v{version}/" not in source:
            raise MatrixError(f"{where}: source does not name v{version}")


def dev_doc_pins(root: Path = ROOT) -> set[str]:
    pins = set()
    for path in sorted(root.glob(DEV_DOC_GLOB)):
        pins.update(VERSION_TAG.findall(path.read_text()))
    return pins


def workbuddy_pins(root: Path = ROOT) -> tuple[str, str]:
    text = (root / WORKBUDDY_DOC).read_text()
    source = WORKBUDDY_SOURCE.search(text)
    version = WORKBUDDY_VERSION.search(text)
    if not source or not version:
        raise MatrixError(f"{WORKBUDDY_DOC}: expected WORKBUDDY_SOURCE and WORKBUDDY_VERSION")
    return version.group(1), source.group(0).split('"')[1]


def render(matrix: dict) -> str:
    validate_matrix(matrix)
    channels = matrix["channels"]
    rows = "\n".join(
        f"| {channel['label']} | `{channel['pluginTag']}` | `{channel['cli']['version']}` | "
        f"`{channel['cli']['distTag']}` | [`{channel['installEntry']}`](../{channel['installEntry']}) |"
        for channel in channels.values()
    )
    host_rows = "\n".join(
        f"| {pin['label']} | `{pin['version']}` | {pin['status']} | {pin['source']} |"
        for pin in matrix["hostPins"].values()
    )
    return f"""# Release channels

<!-- Generated by scripts/release_matrix.py from release-matrix.json. Do not edit by hand. -->

Repository release: **{matrix['repositoryVersion']}** (`VERSION`), updated {matrix['updated']}.

`VERSION` is the repository release. Install pins advance only after their package is
verified, so a pin can intentionally be older than `VERSION`. Do not treat a lower pin as
stale without checking its status below.

| Channel | Plugin release | CLI | npm dist-tag | Install entry |
| --- | --- | --- | --- | --- |
{rows}

## Host pins

| Host | Version | Status | Source |
| --- | --- | --- | --- |
{host_rows}

## What to tell users

- Use the Stable channel unless you were explicitly asked to test development.
- The development channel is pinned to one immutable release; it does not follow `VERSION`.
- A host pin advances only after that host's package has been verified.
"""


def check(root: Path = ROOT) -> list[str]:
    errors = []
    matrix = load_matrix(root)
    try:
        validate_matrix(matrix)
    except MatrixError as error:
        return [str(error)]
    version = (root / "VERSION").read_text().strip()
    if matrix["repositoryVersion"] != version:
        errors.append(
            f"{MATRIX_FILE}: repositoryVersion {matrix['repositoryVersion']!r} != VERSION {version!r}"
        )
    stable = matrix["channels"]["stable"]
    if stable["pluginVersion"] != version:
        errors.append(
            f"{MATRIX_FILE}: stable pluginVersion {stable['pluginVersion']!r} != VERSION {version!r}"
        )
    for channel in matrix["channels"].values():
        if not (root / channel["installEntry"]).is_file():
            errors.append(f"{MATRIX_FILE}: install entry {channel['installEntry']!r} does not exist")
    expected_dev = matrix["channels"]["development"]["pluginTag"]
    pins = dev_doc_pins(root)
    if pins != {expected_dev}:
        errors.append(
            f"development docs pin {sorted(pins) or 'nothing'}, expected {[expected_dev]}"
        )
    try:
        workbuddy_version, workbuddy_source = workbuddy_pins(root)
    except MatrixError as error:
        errors.append(str(error))
    else:
        host = matrix["hostPins"]["workbuddy"]
        if workbuddy_version != host["version"]:
            errors.append(
                f"{WORKBUDDY_DOC}: WORKBUDDY_VERSION {workbuddy_version!r} != matrix {host['version']!r}"
            )
        if workbuddy_source != host["source"]:
            errors.append(f"{WORKBUDDY_DOC}: WORKBUDDY_SOURCE does not match the matrix")
    page = root / PAGE_FILE
    expected_page = render(matrix)
    if not page.is_file():
        errors.append(f"{PAGE_FILE} is missing; run python3 scripts/release_matrix.py --write")
    elif page.read_text() != expected_page:
        errors.append(f"{PAGE_FILE} is stale; run python3 scripts/release_matrix.py --write")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="validate the matrix, pins and page")
    group.add_argument("--write", action="store_true", help="regenerate docs/release-channels.md")
    args = parser.parse_args(argv)
    matrix = load_matrix()
    validate_matrix(matrix)
    if args.write:
        (ROOT / PAGE_FILE).write_text(render(matrix))
        print(f"Wrote {PAGE_FILE}")
        return 0
    if args.check:
        errors = check(ROOT)
        for error in errors:
            print(f"release matrix: {error}", file=sys.stderr)
        if errors:
            return 1
        print("Release matrix: VERSION, channel pins, host pins and page are consistent")
        return 0
    print(render(matrix), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
